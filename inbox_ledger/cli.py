"""Command line: `python -m inbox_ledger <command>`."""
import argparse
import os
from pathlib import Path

from .config import data_dir, open_store
from .sources import Gmail, read_jsonl, read_mbox


def cmd_sync(args):
    store = open_store()
    d = data_dir()
    gmail = Gmail(d / "credentials.json", d / "token.json")
    after = None if args.full else store.latest_message_date()
    total = 0
    for bank in store.banks:
        if bank.gmail_query:
            msgs = list(gmail.fetch(bank.gmail_query, after=after, limit=args.limit))
            total += store.add_messages(msgs)
            print(f"{bank.name}: {len(msgs)} emails fetched")
    print(f"{total} new emails · {store.rebuild()}")


def cmd_import(args):
    store = open_store()
    added = 0
    for p in map(Path, args.files):
        reader = read_mbox if p.suffix == ".mbox" else read_jsonl
        added += store.add_messages(reader(p))
    print(f"{added} new emails · {store.rebuild()}")


def cmd_rebuild(args):
    print(open_store().rebuild())


def cmd_demo(args):
    from .demo import generate
    os.environ["INBOX_LEDGER_DATA"] = str(Path(args.dir).resolve())
    store = open_store()
    (Path(args.dir) / "DEMO").write_text("Synthetic data generated by `inbox_ledger demo`.\n")
    n = store.add_messages(generate(months=args.months, seed=args.seed))
    for category, limit in {"dining": 900, "groceries": 800, "shopping": 600, "taxi": 400, "transport": 300,
                            "subscriptions": 200, "housing": 3500}.items():
        store.set_budget(category, limit)
    print(f"demo: {n} synthetic emails · {store.rebuild()}")


def cmd_serve(args):
    import uvicorn
    print(f"Inbox Ledger → http://{args.host}:{args.port}")
    uvicorn.run("inbox_ledger.api:app", host=args.host, port=args.port, log_level="warning")


def main():
    p = argparse.ArgumentParser(prog="inbox-ledger", description="Budgets from your bank emails.")
    sub = p.add_subparsers(required=True)

    s = sub.add_parser("sync", help="fetch new bank emails from Gmail")
    s.add_argument("--full", action="store_true", help="ignore what is already stored")
    s.add_argument("--limit", type=int, default=2000)
    s.set_defaults(func=cmd_sync)

    s = sub.add_parser("import", help="import emails from .mbox (Google Takeout) or .jsonl")
    s.add_argument("files", nargs="+")
    s.set_defaults(func=cmd_import)

    sub.add_parser("rebuild", help="re-parse and re-categorize everything").set_defaults(func=cmd_rebuild)

    s = sub.add_parser("demo", help="create a demo ledger with synthetic data")
    s.add_argument("--dir", default="demo-data")
    s.add_argument("--months", type=int, default=6)
    s.add_argument("--seed", type=int, default=7)
    s.set_defaults(func=cmd_demo)

    s = sub.add_parser("serve", help="open the dashboard")
    s.add_argument("--host", default="127.0.0.1")
    s.add_argument("--port", type=int, default=8765)
    s.set_defaults(func=cmd_serve)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
